/// Turns AOSP's `keycodes.h` into the `TvKey` enum.
library;

import 'dart:convert';

/// One key code from `keycodes.h`.
typedef KeyCodeEntry = ({String name, int code, String comment});

final RegExp _entry = RegExp(r'^\s*AKEYCODE_([A-Z0-9_]+)\s*=\s*(\d+)\s*,');
final RegExp _commentStart = RegExp(r'^\s*/\*\*');
final RegExp _commentLead = RegExp(r'^\s*\*?\s*');
final RegExp _singleDigit = RegExp(r'^\d$');
final RegExp _leadingDigit = RegExp(r'^\d');

/// The key codes in [header], in file order, each with the first line of the comment above it.
List<KeyCodeEntry> parseKeyCodes(String header) {
  final entries = <KeyCodeEntry>[];
  final comment = <String>[];
  var inComment = false;
  for (final line in LineSplitter.split(header)) {
    if (_commentStart.hasMatch(line)) {
      comment.clear();
      inComment = true;
    }
    if (inComment) {
      comment.add(line);
      if (line.contains('*/')) inComment = false;
      continue;
    }
    final match = _entry.firstMatch(line);
    if (match == null) continue;
    entries.add((name: match[1]!, code: int.parse(match[2]!), comment: summarize(comment.join('\n'))));
    comment.clear();
  }
  return entries;
}

/// The first line of a `/** … */` comment, as one sentence for a doc comment.
String summarize(String comment) {
  final text = comment.replaceAll('/**', '').replaceAll('*/', '');
  final first = text
      .split('\n')
      .map((line) => line.replaceFirst(_commentLead, '').trim())
      .firstWhere((line) => line.isNotEmpty, orElse: () => '');
  final escaped = first.replaceAll('[', r'\[').replaceAll(']', r'\]');
  if (escaped.isEmpty) return 'No description in AOSP.';
  return escaped.endsWith('.') ? escaped : '$escaped.';
}

/// Names that cannot be Dart identifiers as they are, and what they become.
const Map<String, String> fixedNames = {
  '3D_MODE': 'mode3d',
  '11': 'key11',
  '12': 'key12',
  'BREAK': 'breakKey',
  'NEW': 'newKey',
};

/// Dart's reserved words, and the members every enum value already has.
const Set<String> forbiddenNames = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', 'default', 'do', 'else', 'enum', 'extends', //
  'false', 'final', 'finally', 'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super', 'switch', //
  'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with', 'await', 'yield', //
  'code', 'index', 'name', 'values', 'hashCode', 'runtimeType', 'toString', 'noSuchMethod', 'fromCode', //
};

/// The Dart name of AOSP's `AKEYCODE_[name]`: lowerCamelCase, with [fixedNames] and digits `0`-`9` as `digit0`….
///
/// Throws [FormatException] for a name no rule covers (a new leading digit or a reserved word), so it is handled
/// explicitly instead of generated wrong.
String dartName(String name) {
  final fixed = fixedNames[name];
  if (fixed != null) return fixed;
  if (_singleDigit.hasMatch(name)) return 'digit$name';
  if (_leadingDigit.hasMatch(name)) throw FormatException('No rule for a key name starting with a digit', name);
  final words = name.toLowerCase().split('_').where((word) => word.isNotEmpty).toList();
  final camel = words.first + words.skip(1).map((word) => word[0].toUpperCase() + word.substring(1)).join();
  if (forbiddenNames.contains(camel)) throw FormatException('No rule for a reserved key name', name);
  return camel;
}

/// The whole generated Dart file for [entries].
///
/// Throws [FormatException] if two entries get the same Dart name.
String generateKeyCodes(List<KeyCodeEntry> entries) {
  final names = [for (final entry in entries) dartName(entry.name)];
  final seen = <String>{};
  for (final (i, name) in names.indexed) {
    if (!seen.add(name)) throw FormatException('Two keys named $name', entries[i].name);
  }
  final out = StringBuffer(_header);
  for (final (i, entry) in entries.indexed) {
    final last = i == entries.length - 1;
    out
      ..writeln('  /// ${entry.comment}')
      ..writeln('  ${names[i]}(${entry.code})${last ? ';' : ','}');
    if (!last) out.writeln();
  }
  out.write(_footer);
  return out.toString();
}

