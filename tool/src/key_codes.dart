// Copyright 2026 The androidtv_direct authors
// SPDX-License-Identifier: Apache-2.0
//
// Generated by tool/generate_key_codes.dart from AOSP's frameworks/native/include/android/keycodes.h
// (Copyright (C) 2010 The Android Open Source Project, Apache-2.0). Do not edit; run the generator.

/// Android's key codes, as a TV takes them.
///
/// Names are AOSP's `AKEYCODE_…` names in lowerCamelCase; `digit0` to `digit9` are the number keys, `key11` and
/// `key12` the keys 11 and 12, `mode3d`, `breakKey` and `newKey` the keys `3D_MODE`, `BREAK` and `NEW`. A TV may
/// ignore keys its Android version does not know.
enum TvKey {
''';

const String _footer = '''

  const TvKey(this.code);

  /// The Android key code.
  final int code;

  static final Map<int, TvKey> _byCode = {for (final key in values) key.code: key};

  /// The key with Android key code [code], or `null` if the table does not have it.
  static TvKey? fromCode(int code) => _byCode[code];
}
''';
